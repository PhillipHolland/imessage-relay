#!/usr/bin/env python3
"""Packs bundle/ into a single self-contained build_bundle.py (every file as embedded text).
Usage: python3 tools/pack.py [bundle_dir] [out_file]"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'bundle'))
OUT = os.path.abspath(sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'build_bundle.py'))
SKIP_DIRS = {'__pycache__', 'node_modules', '.git'}
MARK = '@@@@ '

HEADER = '''#!/usr/bin/env python3
"""
build_bundle.py: iMessage Relay v1.4.3, the whole package in one file (no repo needed).

    python3 build_bundle.py OUT_DIR            write every file into OUT_DIR (must be empty or absent)
    python3 build_bundle.py OUT_DIR --force    overwrite files in an existing OUT_DIR
    python3 build_bundle.py --list             list embedded files with sizes and sha256
    python3 build_bundle.py OUT_DIR --no-tests skip tests/ (enough to install on a Mac)

Then on the Mac:  cd OUT_DIR && ./install.sh --owner-handle "+1 555 555 0123"
Each file is checked against its embedded sha256 after writing. Standard library only.
Generated by tools/pack.py from the source tree; do not edit by hand.
"""
import hashlib
import os
import sys

BUNDLE = r\'\'\''''

FOOTER = '''\'\'\'


def parse(blob=BUNDLE):
    files, lines, cur = [], blob.split('\\n'), None
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('@@@@ FILE '):
            parts = line[len('@@@@ FILE '):].split(' ')
            meta = dict(p.split('=', 1) for p in parts[1:])
            body = []
            i += 1
            while not lines[i].startswith('@@@@ END'):
                body.append(lines[i])
                i += 1
            text = '\\n'.join(body) + ('' if meta.get('nl') == '0' else '\\n')
            files.append((parts[0], int(meta['mode'], 8), meta['sha256'], text))
        i += 1
    return files


def main(argv):
    files = parse()
    if '--list' in argv:
        for path, mode, sha, text in files:
            print('%8d  %s  %s' % (len(text.encode('utf-8')), sha[:12], path))
        print('%d files' % len(files))
        return 0
    args = [a for a in argv if not a.startswith('--')]
    if not args:
        print(__doc__)
        return 1
    out = os.path.abspath(os.path.expanduser(args[0]))
    if os.path.isdir(out) and os.listdir(out) and '--force' not in argv:
        print('error: %s is not empty (use --force)' % out)
        return 1
    n = 0
    for path, mode, sha, text in files:
        if '--no-tests' in argv and path.startswith('tests/'):
            continue
        if os.path.isabs(path) or '..' in path.split('/'):
            raise SystemExit('refusing unsafe path: ' + path)
        data = text.encode('utf-8')
        if hashlib.sha256(data).hexdigest() != sha:
            raise SystemExit('checksum mismatch in embedded file: ' + path)
        dest = os.path.join(out, *path.split('/'))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, 'wb') as f:
            f.write(data)
        os.chmod(dest, mode)
        n += 1
    print('wrote %d files to %s' % (n, out))
    print('next (on the Mac): cd "%s" && ./install.sh --owner-handle "<your number>"' % out)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
'''


def collect():
    out = []
    for root, dirs, files in os.walk(SRC):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for f in sorted(files):
            if f.endswith('.pyc'):
                continue
            p = os.path.join(root, f)
            out.append((os.path.relpath(p, SRC).replace(os.sep, '/'), p))
    return out


def main():
    parts = []
    for rel, p in collect():
        with open(p, 'rb') as f:
            data = f.read()
        text = data.decode('utf-8')        # text files only
        if "'''" in text:
            raise SystemExit("%s contains ''' (cannot embed in a raw string)" % rel)
        if any(l.startswith(MARK) for l in text.split('\n')):
            raise SystemExit('%s has a line starting with the marker' % rel)
        if ' ' in rel:
            raise SystemExit('space in path: ' + rel)
        base = rel.rsplit('/', 1)[-1]
        # Explicit, filesystem-independent modes so the bundle is deterministic (item 15): shell
        # scripts and the directly-executed Python entry points are 755, everything else 644.
        executable = rel.endswith('.sh') or base in ('imessage_relay_host.py', 'imessage_relay_watch.py',
                                                      'watch_launcher.py', 'relayctl.py')
        mode = '755' if executable else '644'
        nl = text.endswith('\n')
        body = text[:-1] if nl else text
        parts.append('%sFILE %s mode=%s sha256=%s nl=%d\n%s\n%sEND' % (MARK, rel, mode, hashlib.sha256(data).hexdigest(), int(nl), body, MARK))
    blob = '\n' + '\n'.join(parts) + '\n'
    if blob.rstrip('\n').endswith('\\'):
        raise SystemExit('blob ends with a backslash')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(HEADER + blob + FOOTER)
    os.chmod(OUT, 0o755)
    print('packed %d files into %s (%d bytes)' % (len(parts), OUT, os.path.getsize(OUT)))


if __name__ == '__main__':
    main()
